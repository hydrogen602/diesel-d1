use std::fs::File;
use std::io::Write;

use integration_tester::ALL_TESTS;

/// This is meant to be run on the host, not wasm.
fn main() {
    let mut file = File::create("tests.gen.py").unwrap();
    macro_rules! line {
        ($($arg:tt)*) => {
            writeln!(file, $($arg)*).unwrap();
        };
    }
    line!("#!/usr/bin/env python3");
    line!("");
    line!("# Generated by integration-tester/src/bin/gen_py_tests.rs");
    line!("# Do not edit this file manually");
    line!("import os");
    line!("import unittest");
    line!("import urllib.request");
    line!("");
    line!("BASE_URL = os.getenv('BASE_URL', 'http://localhost:8787/')");
    line!("BASE_URL = BASE_URL.rstrip('/') + '/' # Guarantee trailing slash");
    line!("");
    line!("class TestIntegration(unittest.TestCase):");
    line!("");
    for &test in ALL_TESTS {
        line!("  def {}(self):", test);
        line!("    with urllib.request.urlopen(f'{{BASE_URL}}{test}') as response:");
        line!("      self.assertEqual(response.read().decode('utf-8'), '{test} passed')");
        line!("");
    }
    line!("");
    line!("if __name__ == '__main__':");
    line!("    unittest.main()");
}
